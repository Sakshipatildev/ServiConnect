IF DB_ID('ServiConnect') IS NULL CREATE DATABASE ServiConnect;
GO
USE ServiConnect;
GO
CREATE TABLE Users(
 Id BIGINT IDENTITY PRIMARY KEY, FullName NVARCHAR(100) NOT NULL,
 Email NVARCHAR(150) NOT NULL UNIQUE, PasswordHash NVARCHAR(100) NOT NULL,
 Role NVARCHAR(20) NOT NULL CHECK(Role IN ('CUSTOMER','PROVIDER')),
 Phone NVARCHAR(20), CreatedAt DATETIME2 DEFAULT SYSUTCDATETIME()
);
CREATE TABLE Services(
 Id BIGINT IDENTITY PRIMARY KEY, ProviderId BIGINT NOT NULL REFERENCES Users(Id),
 Category NVARCHAR(50) NOT NULL, Title NVARCHAR(120) NOT NULL,
 Description NVARCHAR(1000), PricingType NVARCHAR(20) NOT NULL CHECK(PricingType IN ('FIXED','HOURLY')),
 Price DECIMAL(10,2) NOT NULL CHECK(Price>=0), IsActive BIT DEFAULT 1
);
CREATE TABLE Bookings(
 Id BIGINT IDENTITY PRIMARY KEY, CustomerId BIGINT NOT NULL REFERENCES Users(Id),
 ProviderId BIGINT NOT NULL REFERENCES Users(Id), ServiceId BIGINT NOT NULL REFERENCES Services(Id),
 BookingDate DATE NOT NULL, StartTime TIME NOT NULL, EndTime TIME NOT NULL,
 Address NVARCHAR(300) NOT NULL, Notes NVARCHAR(1000),
 Status NVARCHAR(20) DEFAULT 'PENDING' CHECK(Status IN ('PENDING','ACCEPTED','REJECTED','CANCELLED','COMPLETED')),
 CreatedAt DATETIME2 DEFAULT SYSUTCDATETIME(), CHECK(EndTime>StartTime)
);
